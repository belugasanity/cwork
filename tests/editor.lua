vim.api.nvim_create_autocmd('VimEnter', { once = true, callback = function()
  vim.schedule(function()
    local ok, error = xpcall(function()
      local S, api = Cwork, vim.api
      local function wait_for(fn, message) assert(vim.wait(7000, fn, 30), message) end
      local function text(buf) return table.concat(api.nvim_buf_get_lines(buf, 0, -1, false), '\n') end
      assert(api.nvim_win_is_valid(S.edit_win) and api.nvim_win_is_valid(S.term_win), 'Two native terminal windows must exist')
      assert(S.job > 0, 'PTY shell job must start')
      vim.fn.chansend(S.job, 'echo CWORK_PTY_OK\r')
      wait_for(function() return text(S.term_buf):find('CWORK_PTY_OK', 1, true) end, 'Terminal must receive input and render output')
      wait_for(function() return #S.changes == 3 end, 'Git changes must include modified, deleted and new files')
      S.browser('files')
      assert(text(S.nav_buf):find('src/', 1, true), 'Browser must list folders')
      S.expanded.src = true; S.render()
      assert(text(S.nav_buf):find('hello.ts', 1, true), 'Browser must expand folders')
      S.open_file('src/hello.ts')
      assert(vim.bo[S.file_buf].filetype == 'typescript', 'Filetype syntax must match TypeScript')
      assert(vim.bo[S.file_buf].syntax ~= '', 'File syntax rules must be active')
      assert(text(S.file_buf):find('count = 2', 1, true), 'Viewer must show working tree content')
      S.diff()
      wait_for(function() return S.diff_buf and text(S.diff_buf):find('count = 1', 1, true) end, 'HEAD diff must display original content')
      assert(vim.bo[S.diff_buf].filetype == 'typescript', 'HEAD diff must have syntax highlighting')
      assert(not vim.bo[S.diff_buf].modifiable, 'HEAD must be read only')
      local edit_window, diff_window = S.edit_win, S.diff_win
      S.help()
      assert(api.nvim_win_is_valid(S.help_win), 'Shortcuts must open in a popup')
      assert(api.nvim_win_get_config(S.help_win).relative == 'editor', 'Shortcuts must use an overlay')
      assert(text(S.help_buf):find('SEARCH / REPLACE', 1, true), 'Shortcuts must include search and replace')
      assert(text(S.help_buf):find('VISUAL SELECTION', 1, true), 'Shortcuts must include selection and copying')
      assert(not vim.bo[S.help_buf].modifiable and vim.bo[S.help_buf].readonly, 'Reference must be read only')
      assert(vim.fn.search('VISUAL SELECTION', 'w') > 0, 'Reference must support native text search')
      S.help() -- F1 toggles the same popup closed.
      assert(not S.help_win and api.nvim_get_current_win() == edit_window, 'Closing must restore the previous pane')
      assert(api.nvim_win_is_valid(diff_window), 'Viewing shortcuts must preserve the diff layout')
      assert(api.nvim_get_commands({}).Shortcuts, 'The :Shortcuts command must be available')
      S.close_diff()
      -- Real editing and saving, rather than a read-only preview.
      api.nvim_buf_set_lines(S.file_buf, 0, -1, false, { 'export const count = 3;' })
      api.nvim_buf_call(S.file_buf, function() vim.cmd.write() end)
      assert(vim.fn.readfile(S.root .. '/src/hello.ts')[1] == 'export const count = 3;', 'Edits must save to disk')
      -- External edits must reload without overwriting unsaved buffers.
      vim.fn.writefile({ 'export const count = 4;' }, S.root .. '/src/hello.ts')
      wait_for(function() return text(S.file_buf):find('count = 4', 1, true) end, 'External file changes must reload')
      api.nvim_buf_set_lines(S.file_buf, 0, -1, false, { 'export const unsaved = true;' })
      S.help(); S.close_help()
      assert(vim.bo[S.file_buf].modified and text(S.file_buf):find('unsaved', 1, true), 'Shortcut popup must preserve unsaved edits')
      vim.fn.writefile({ 'export const external = true;' }, S.root .. '/src/hello.ts')
      vim.wait(2200)
      assert(text(S.file_buf):find('unsaved', 1, true), 'External edits must preserve unsaved changes')
      vim.bo[S.file_buf].modified = false
      S.open_file('deleted.py'); S.diff()
      wait_for(function() return S.diff_buf and text(S.diff_buf):find('deleted', 1, true) end, 'Deleted file must show HEAD content')
      S.open_file('new.json'); S.diff()
      wait_for(function() return S.diff_buf and api.nvim_buf_is_valid(S.diff_buf) end, 'New file must show an empty HEAD baseline')
      assert(text(S.diff_buf) == '', 'Untracked file baseline must be empty')
      assert(vim.bo[S.file_buf].filetype == 'json', 'New files must use syntax highlighting')
      S.browser('changes')
      assert(text(S.nav_buf):find('deleted.py', 1, true), 'Change browser must list deleted files')
      print('PASS: terminal input, split layout, file browser, editing/saving, syntax, HEAD diffs, live reload, searchable shortcuts, unsaved edit preservation, deleted/new files.')
    end, debug.traceback)
    if Cwork.job and Cwork.job > 0 then vim.fn.jobstop(Cwork.job); vim.fn.jobwait({ Cwork.job }, 1000) end
    if not ok then io.stderr:write(tostring(error) .. '\n'); vim.cmd('cquit 1') else vim.cmd('qa!') end
  end)
end })
